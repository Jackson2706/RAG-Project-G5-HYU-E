#!/usr/bin/env python
"""Regenerate files derived from the method/hyperparameter registry. Run after changing app/rag/registry.py:

    conda activate RAG
    python scripts/export_registry.py

Writes:
  docs/HYPERPARAMETERS.md (the section between the REGISTRY-TABLE markers)
  frontend/src/test/registry.fixture.json (fixture for the frontend tests)
"""

from __future__ import annotations

import json
import re
from pathlib import Path

import _bootstrap  # noqa: F401  (sets the import path)

from app.rag.registry import ONLINE_STAGES, OFFLINE_STAGES, registry_payload

ROOT = Path(__file__).resolve().parent.parent
DOC = ROOT / "docs" / "HYPERPARAMETERS.md"
FIXTURE = ROOT / "frontend" / "src" / "test" / "registry.fixture.json"
START, END = "<!-- REGISTRY-TABLE:START -->", "<!-- REGISTRY-TABLE:END -->"


def fmt(v) -> str:
    if v is None or v == "" or v == []:
        return "—"
    s = json.dumps(v) if isinstance(v, (list, bool)) else str(v)
    return s if len(s) <= 40 else s[:37] + "…"


def table() -> str:
    lines = [START, "", "_Generated by `python scripts/export_registry.py` — do not edit by hand._", ""]
    for title, stages in (("Online stages (runtime)", ONLINE_STAGES), ("Offline stages (ingestion / index)", OFFLINE_STAGES)):
        lines += [f"### {title}", ""]
        for s in stages:
            lines += [f"#### {s.stage_name} (`{s.stage_id}`)", ""]
            lines.append("Methods: " + ", ".join(f"`{m.method_id}` ({m.status.value})" for m in s.available_methods))
            lines.append("")
            rows = [(m, p) for m in s.available_methods for p in m.parameters]
            if not rows:
                lines += ["No hyperparameters.", ""]
                continue
            lines += ["| Method | Parameter | Type | Default | Range / options | Scope | Level | Meaning |", "|---|---|---|---|---|---|---|---|"]
            for m, p in rows:
                if p.options:
                    rng = ", ".join(str(o.value) for o in p.options)
                elif p.min is not None or p.max is not None:
                    rng = f"{fmt(p.min)} … {fmt(p.max)}" + (f" (step {fmt(p.step)})" if p.step else "")
                else:
                    rng = "—"
                desc = p.description.replace("|", "\\|")
                lines.append(f"| `{m.method_id}` | `{p.name}` | {p.type.value} | {fmt(p.default)} | {rng} | {p.scope.value} | {p.level} | {desc} |")
            lines.append("")
    lines.append(END)
    return "\n".join(lines)


def main() -> None:
    FIXTURE.write_text(json.dumps(registry_payload(), indent=1) + "\n", encoding="utf-8")
    text = DOC.read_text(encoding="utf-8")
    new = re.sub(re.escape(START) + r".*?" + re.escape(END), table(), text, flags=re.S)
    if new == text and START not in text:
        raise SystemExit(f"{DOC} has no {START} … {END} markers")
    DOC.write_text(new, encoding="utf-8")
    print(f"updated {FIXTURE.relative_to(ROOT)} and {DOC.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
