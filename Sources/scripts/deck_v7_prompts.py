"""Deck v7: write Report/slides/deck_v4/aaes_prompts.md, the exact prompt texts of every AAES LLM option.

Run from Sources/:  python scripts/deck_v7_prompts.py
Every prompt is imported from the code that sends it (no copy), with its SHA-256, so the file cannot drift from the
system. Per-case notes and fixed replies are rendered once with example values (marked as examples).
"""

from __future__ import annotations

import hashlib
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "Sources" / "backend"))
from app.rag import aaes, aaes_llm  # noqa: E402
from app.rag.blocks.evidence.evidence_sufficiency.applicability_sufficiency import ApplicabilitySufficiency  # noqa: E402
from app.rag.blocks.grounded_generation.context_construction import standard_context  # noqa: E402
from app.rag.reply_cleanup import OTHER_CASES  # noqa: E402

OUT = ROOT / "Report" / "slides" / "deck_v4" / "aaes_prompts.md"


def block(name: str, text: str, where: str) -> list[str]:
    return [f"### {name}", "", f"{where}  ", f"SHA-256 `{hashlib.sha256(text.encode()).hexdigest()[:16]}…`", "", "```text", text, "```", ""]


def main() -> int:
    example_decision = {"branch_attributes": ["campus"], "branch_table": [{"when": {"campus": ["seoul"]}, "evidence": ["c1"]},
                                                                          {"when": {"campus": ["erica"]}, "evidence": []}]}  # fmt: skip
    rules_note = aaes.branch_note(example_decision, ["c1"])
    llm_note = ApplicabilitySufficiency._answers_note(None, "campus", {"seoul": "apply online", "erica": "apply at the office"})  # type: ignore[arg-type]
    clarify = aaes.render_action({"action": "CLARIFY", "clarify_attribute": "campus", "branches": {}, "reason": ""}, {})
    abstain = aaes.render_action({"action": "ABSTAIN", "reason": "not_applicable"}, {"campus": {"values": ["seoul"]}})
    lines = [
        "# AAES prompts (exact texts, generated from the code)", "",
        "Generated by `Sources/scripts/deck_v7_prompts.py` from the modules that send each prompt. Model for every call:",
        "`qwen3.5:4b` through Ollama, temperature 0, seed 42, thinking off, 4,096-token context (`aaes_llm.call`); each",
        "AAES LLM call is one system message (the prompt below) and one user message (built as described).", "",
        "## Which prompt each option uses", "",
        "| Step | rules (R) | LLM (L) | both (B) |", "|---|---|---|---|",
        "| 1 Read the student | regex rules (`aaes.extract_profile`), no LLM | PROFILE | rules first; a hypothetical or mentioned value needs PROFILE's confirmation; PROFILE fills missing attributes |",
        "| 2 Does each passage apply | metadata tags (`aaes.label_chunk`), no LLM | APPLIES (labels and relevance of the top 6 passages) | tags first; APPLIES runs on the top 6, its label is used only where the tag is unknown; relevant = overlap or APPLIES |",
        "| 3 Which detail matters | applicable-chunk branches (`aaes.decide`), no LLM | DIFFERS (+ its per-case note for the writer) | rule branches, then EXTRACT per evidence set and SAME to merge branches with the same answer |",
        "| 4 Decide the reply | rule policy (`aaes.decide`), fixed templates | DECIDE | rule decision; ASK or REFER words the question or referral |",
        "", "AAES+ as frozen (`AP_RRRL`) uses rules in Steps 1–3 and DECIDE in Step 4, then the writer.", "",
        "## Step 1 · PROFILE (L, B)", "",
        *block("PROFILE", aaes_llm.PROFILE, "User message: `Earlier: <each earlier turn>` lines, then `Now: <question>`. Code: `profile_understanding.py`."),
        "## Step 2 · APPLIES (L, B)", "",
        *block("APPLIES", aaes_llm.APPLIES, "User message: `Question: …`, `Known about the student: …`, then `[P1]` … `[P6]` passages (1,200 characters each). Code: `applicability_reranker.py`."),
        "## Step 3 · DIFFERS (L); EXTRACT and SAME (B)", "",
        *block("DIFFERS", aaes_llm.DIFFERS, "User message: question, known details, passages as `[P#] (campus: …; for: …)`. Code: `applicability_sufficiency._llm_branches`."),
        *block("EXTRACT", aaes_llm.EXTRACT, "User message: `Question: …` and the evidence of one branch (1,500 characters per chunk). Code: `_extract_branches`."),
        *block("SAME", aaes_llm.SAME, "User message: `Question: …` and the extracted answers as `[G1] …`, `[G2] …`. Called only when the answers differ and contain no different numbers."),
        "## Step 4 · DECIDE (L); ASK and REFER (B)", "",
        *block("DECIDE", aaes_llm.DECIDE, "User message: question, known details, Step 3's result, passages. Code: `applicability_sufficiency._llm_decide`."),
        *block("ASK (template)", aaes_llm.ASK, "Filled with the detail's name and options; user message: the passages. Code: `_llm_wording`."),
        *block("REFER (template)", aaes_llm.REFER, "Filled with the campus office; user message: the passages."),
        "## Writer (all AAES versions and B0)", "",
        *block("standard_context.SYSTEM_PROMPT", standard_context.SYSTEM_PROMPT,
               "User message: `Evidence:` with `[E1] title — section — page` blocks, then `Question: …`. For an answer per case the question is followed by the per-case note below."),
        *block("Per-case note, rules Step 3 (example values)", rules_note, "`aaes.branch_note`: one line per branch, with the evidence labels it may use."),
        *block("Per-case note, LLM Step 3 (example values)", llm_note, "`ApplicabilitySufficiency._answers_note`: DIFFERS's answer per value."),
        "## Fixed replies (no LLM; Step 4 rules)", "",
        *block("CLARIFY (example)", clarify, "`aaes.render_action`."),
        *block("ABSTAIN, not applicable (example)", abstain, "`aaes.render_action`."),
        *block("Reply cleanup closing line (app only)", OTHER_CASES, "`reply_cleanup.OTHER_CASES`, added after merging cases that only say to ask the office."),
    ]  # fmt: skip
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("wrote", OUT, len(lines), "lines")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
